/** Resolve a roster player from an award / MVP name string. */
window.RRFC_resolveAwardPlayer = (rawName) => {
  if (!rawName || rawName === "N/A") return null;
  try {
    if (window.RRFC_findPlayerByName) {
      return window.RRFC_findPlayerByName(rawName);
    }
  } catch {
    /* fall through */
  }
  const players = window.RRFC_PLAYERS || [];
  const target = String(rawName).trim().toLowerCase();
  return players.find((p) => p.name.toLowerCase() === target) || null;
};

/** Link to a player card when the name matches a roster entry. */
window.RRFC_playerNameHtml = (rawName, className = "") => {
  const safe = String(rawName || "");
  const player = window.RRFC_resolveAwardPlayer(safe);
  const cls = className ? ` class="${className}"` : "";
  if (!player) return `<span${cls}>${safe}</span>`;
  const href = `player.html?name=${encodeURIComponent(player.name)}`;
  return `<a${cls} href="${href}">${safe}</a>`;
};

/**
 * Collect championship rings + season awards + Chip MVPs for a player.
 * Returns badge-shaped objects: { label, team?, short, title }.
 */
window.RRFC_awardsForPlayer = (rawName) => {
  const player = window.RRFC_resolveAwardPlayer(rawName);
  if (!player) return [];

  const matches = (winner) => {
    if (!winner || winner === "N/A") return false;
    const resolved = window.RRFC_resolveAwardPlayer(winner);
    return resolved && resolved.name === player.name;
  };

  const labels = window.RRFC_AWARD_LABELS || {};
  const order = window.RRFC_AWARD_ORDER || Object.keys(labels);
  const out = [];
  const seen = new Set();

  const push = (badge) => {
    const key = `${badge.label}|${badge.team || ""}`;
    if (seen.has(key)) return;
    seen.add(key);
    out.push(badge);
  };

  const rrfcChips = window.RRFC_CHAMPIONSHIPS && window.RRFC_CHAMPIONSHIPS.rrfc;
  const teamLabelMap = window.RRFC_CHAMPION_TEAM_LABEL || {};
  const chipBySeason = new Map(
    (rrfcChips || []).map((s) => [s.season, s])
  );

  const chipRosters = [...(window.RRFC_CHAMPIONSHIP_ROSTERS || [])].sort(
    (a, b) => b.season - a.season
  );
  for (const entry of chipRosters) {
    if (!(entry.roster || []).some((name) => matches(name))) continue;
    const chip = chipBySeason.get(entry.season);
    const rawTeam = chip ? chip.champion : "";
    const team = teamLabelMap[rawTeam] || rawTeam;
    push({
      label: `Season ${entry.season} Champion`,
      short: `S${entry.season} Champ`,
      title: team
        ? `Season ${entry.season} Champion · ${team}`
        : `Season ${entry.season} Champion`,
      team,
    });
  }

  for (const season of window.RRFC_SEASON_AWARDS || []) {
    for (const key of order) {
      const winner = season.awards && season.awards[key];
      if (!matches(winner)) continue;
      const full = labels[key] || key;
      push({
        label: `Season ${season.season} ${key}`,
        short: `S${season.season} ${key}`,
        title: `Season ${season.season} · ${full}`,
      });
    }
  }

  const leagues = window.RRFC_LEAGUES || [];
  const leagueName = (id) => {
    const league = leagues.find((l) => l.id === id);
    return league ? league.name : String(id || "").toUpperCase();
  };

  for (const [leagueId, seasons] of Object.entries(
    window.RRFC_CHAMPIONSHIPS || {}
  )) {
    for (const s of seasons || []) {
      if (!matches(s.mvp)) continue;
      const league = leagueName(leagueId);
      push({
        label: `${league} S${s.season} Chip MVP`,
        short: `S${s.season} Chip MVP`,
        title: `${league} Season ${s.season} Chip MVP · ${s.champion}`,
        team: teamLabelMap[s.champion] || s.champion,
      });
    }
  }

  return out;
};
